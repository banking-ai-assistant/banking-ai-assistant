def find_template_by_style(style: str, loader: TemplateLoader):
    templates = loader.load_all_templates()
    for t_type, data in templates.items():
        for template in data.get("templates", []):
            if template["style"] == style:
                return template
    return None

def llm_judge(engine, input_letter: str, response: str) -> dict:
    prompt = f"""
Ты — эксперт по деловой переписке в банке. Оцени ответ СТРОГО и ОБЪЕКТИВНО по трём критериям (1–5):

КРИТЕРИИ:
1. Релевантность: Ответ ли на вопрос клиента? Игнорирует ли суть?
   → 1 = полностью игнорирует, 5 = точно в цель.
2. Профессионализм: Есть ли вежливость, деловой стиль, ошибки?
   → 1 = грубость/ошибки, 5 = идеальный банковский стиль.
3. Полнота: Учтены ли все ключевые моменты из запроса?
   → 1 = ничего не ответил, 5 = всё учтено.

ПРИМЕР НИЗКОЙ ОЦЕНКИ:
Вход: "Пропали деньги со счёта!"
Ответ: "Спасибо за обращение."
→ {{"relevance": 1, "professionalism": 3, "completeness": 1}}

ТВОЯ ЗАДАЧА:
Входящее письмо: {input_letter}
Ответ банка: {response}

Оцени ЧЕСТНО. Не завышай! Если ответ шаблонный — ставь 2–3.
Ответь ТОЛЬКО JSON, без пояснений:
"""
    try:
        result = engine.client.responses.create(
            model=engine.model,
            instructions="Ты — строгий оценщик. Ответь ТОЛЬКО валидным JSON. Никаких других слов.",
            input=prompt
        )
        raw_text = result.output_text.strip()
        
        import re
        json_match = re.search(r'\{.*\}', raw_text, re.DOTALL)
        if json_match:
            json_str = json_match.group(0)
            return json.loads(json_str)
        else:
            raise ValueError("No JSON found in response")
            
    except Exception as e:
        print(f"Ошибка LLM-judge: {e} | Ответ был: '{result.output_text if 'result' in locals() else 'NO_RESPONSE'}'")
        return {"relevance": 2, "professionalism": 2, "completeness": 2}

def main():
    engine = RAGEngine()
    loader = TemplateLoader()
    
    all_results = []
    
    for i, (letter, action) in enumerate(TEST_CASES, 1):
        print(f"[{i}/{len(TEST_CASES)}] Обработка: {letter[:50]}...")
        
        options = engine.generate_response_options(letter, action)
        
        for opt in options:
            template = find_template_by_style(opt["style"], loader)
            struct_score = {"score": 0, "details": []}
            
            if template:
                struct_score = evaluate_by_template(opt["content"], template)
            
            llm_scores = llm_judge(engine, letter, opt["content"])
            
            all_results.append({
                "input": letter,
                "intent": action,
                "style": opt["style"],
                "content": opt["content"],
                "relevance": llm_scores["relevance"],
                "professionalism": llm_scores["professionalism"],
                "completeness": llm_scores["completeness"]
            })
    
    total = len(all_results)
    avg_relevance = sum(r["relevance"] for r in all_results) / total
    avg_prof = sum(r["professionalism"] for r in all_results) / total
    avg_complete = sum(r["completeness"] for r in all_results) / total
    
    print("\n" + "="*60)
    print("ИТОГОВАЯ ОЦЕНКА")
    print("="*60)
    print(f"Всего ответов: {total}")
    print(f"Средняя релевантность:   {avg_relevance:.2f}")
    print(f"Средний профессионализм: {avg_prof:.2f}")
    print(f"Средняя полнота:         {avg_complete:.2f}")
    
    with open("results.json", "w", encoding="utf-8") as f:
        json.dump(all_results, f, ensure_ascii=False, indent=2)
    
    print("\nРезультаты сохранены в results.json")

if __name__ == "__main__":
    main()